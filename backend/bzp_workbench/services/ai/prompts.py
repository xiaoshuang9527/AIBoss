"""System Prompts 集中定义。

为什么全部放一个文件
--------------------
Prompt 是这套系统里最容易变、最需要评审的部分。散落在各服务文件里会
导致「改了哪里、为什么改」无法追溯。集中定义后可以整体 review 与 diff。

约定
----
* 每个 prompt 都是**纯字符串常量**，不拼接变量；需要动态注入的内容
  （历史、槽位台账、附件）由调用方追加为独立消息或文本块，
  这样 prompt 本身保持稳定，便于回归对比。
* 写 prompt 时优先写「不要做什么」——模型的默认倾向是长篇大论和编造，
  明确禁止比正面要求更有效。
"""

